# 审批层级词汇，填 {层1}/{层2} 用
_LEVELS_1 = ["部门负责人", "直属主管", "部门经理"]
_LEVELS_2 = ["分管副总", "总经理", "分管副总经理"]

_CLAUSE_RE = re.compile(r"\{([^}]+)\}")


def _fill(template: str, rng: random.Random) -> str:
    """把条款骨架里的 `{占位符}` 按随机数填成具体事实。

    占位符的命名规则（前缀决定取值范围）：

    - `金额600` / `金额1000` / `金额1`：金额，基准值 + 小幅抖动（保留整百/整千）；
    - `pct` / `pct2` / `系数`：比例；
    - 其余按名称走 _POOLS 表或默认数字池。
    """

    def repl(match: re.Match) -> str:
        key = match.group(1)
        if key.startswith("金额"):
            base = int(key[2:])
            return str(_round_amount(base, rng))
        if key.startswith("层1"):
            return rng.choice(_LEVELS_1)
        if key.startswith("层2"):
            return rng.choice(_LEVELS_2)
        if key in ("pct", "pct2", "pct3"):
            # 比例：只用常见档位，避免出现 37% 这种不真实的值
            return str(rng.choice([10, 15, 20, 25, 30, 50, 60, 70, 80, 90]))
        if key in _POOLS:
            return str(rng.choice(_POOLS[key]))
        # 默认：小整数
        return str(rng.randint(1, 12))

    return _CLAUSE_RE.sub(repl, template)


