def _copy_base_corpus(base_dir: Path, out_dir: Path) -> list[Path]:
    """把原始标准语料复制进目标目录，返回复制过去的文件列表。

    README / 下划线开头的临时文件不算语料（与 `rebuild_kb.py` 的过滤规则一致）。
    """
    if not base_dir.is_dir():
        raise FileNotFoundError(f"原始语料目录不存在：{base_dir}")
    copied: list[Path] = []
    for path in sorted(base_dir.iterdir()):
        if not path.is_file() or path.name.lower().startswith(("readme", "_", ".")):
            continue
        if path.suffix.lower() not in SUPPORTED_SUFFIXES:
            continue
        target = out_dir / path.name
        if target.exists():
            raise FileExistsError(
                f"目标目录已存在同名文件，拒绝覆盖（可能是重复生成）：{target}"
            )
        shutil.copy2(path, target)
        copied.append(target)
    return copied


