def _round_amount(base: int, rng: random.Random) -> int:
    """金额抖动：小额保留整百，万元级取整千，读起来才像真实制度。"""
    if base >= 10000:
        return base + rng.choice([0, 0, 5000, 10000])
    if base >= 1000:
        return base + rng.choice([0, 0, 500, 1000])
    if base >= 100:
        return base + rng.choice([0, 0, 50, 100])
    return base + rng.choice([0, 0, 1, 2])


def _doc_text(index: int, dept: str, topic: dict, rng: random.Random, target: int) -> str:
    """生成一篇制度文档的完整文本。

    组装顺序固定为「抬头 → 总则 → 正文条款 → 尾段条款 → 附则」，
    长度通过**填充条款条数**逼近 `target`，最终保证落在 800~1500 字。

    Args:
        index: 文件序号（写进文件编号）。
        dept: 归属部门。
        topic: 主题定义（含名称、适用范围、条款骨架池）。
        rng: 该篇专属的随机数发生器（种子由主流程给出，保证可复现）。
        target: 目标字数，正文条款数量会围绕它收敛。
    """
    name = topic["name"]
    suffix = "细则" if "细则" in name else ("办法" if "办法" in name else "规定")
    subject = (name.replace("细则", "").replace("规定", "").replace("办法", "")
               .replace("规范", "").replace("制度", ""))

    # 该篇专属的取值：生效日期、条款顺序、每条条款的具体数值
    effective = f"2026年{rng.randint(1, 12)}月{rng.randint(1, 28)}日"
    header = (
        f"《{dept}{name}》\n\n"
        f"文件编号：ZD-{dept[:2]}-{index:03d}    生效日期：{effective}\n\n"
        f"第一条 为规范{dept}{subject}相关管理，明确职责边界与操作要求，"
        f"依据公司《员工手册》及国家相关法律法规，制定本{suffix}。\n\n"
    )

    scope = (
        f"第二条 本{suffix}适用于{dept}全体在职员工、"
        f"实习生及经授权参与相关业务的外部合作人员，涵盖{topic['scope']}等事项。\n\n"
        f"第三条 本{suffix}遵循「先审批、后执行，谁经办、谁负责」原则，"
        f"各环节记录应完整留痕，作为后续核查与审计依据。\n\n"
    )

    # 尾段补充条款池：真实制度里常见的程序性要求（执行留痕 / 数据核对 / 例外处理）
    procedure_pool = [
        f"本{suffix}涉及的事项应通过{dept}内部审批系统办理，审批环节、经办人与时间节点"
        f"由系统自动记录；紧急事项来不及线上审批的，可先行取得{_LEVELS_2[0]}口头同意，"
        f"但须在{_POOLS['时限'][2]}个工作日内补办手续，并在台账中注明紧急事由。",
        f"{dept}应建立与本{suffix}配套的执行台账，按月收集数据、按季度自查；"
        f"自查发现偏差的，责任岗位须在{_POOLS['时限'][2]}个工作日内提交原因分析，"
        f"偏差影响金额超过{_POOLS['金额1'][3]}万元的同步报送{_LEVELS_2[0]}。",
        f"涉及本{suffix}的原始凭证、审批单与会议记录，由{dept}归口保存不少于"
        f"{_POOLS['保留'][2]}个月，保存期满后按档案管理规定统一处置，任何人不得擅自销毁或抽换。",
        f"新入职人员由{dept}在入职后{_POOLS['时限'][0]}个工作日内完成本{suffix}宣导，"
        f"宣导记录纳入员工培训档案；岗位调整涉及职责范围变更的，由{dept}重新确认权限并更新台账。",
        f"外部合作方需要知悉本{suffix}要求的，由{dept}在合作启动前以书面方式告知，"
        f"并在合作协议中约定相应的履约义务，履约情况纳入年度供应商评价。",
    ]

    # 先把条款正文一次性填好（只填一次，保证同样的种子得到同样的文本）
    clauses = list(topic["clauses"])
    rng.shuffle(clauses)
    filled_body = [f"{_fill(t, rng)}\n" for t in clauses]
    rng.shuffle(procedure_pool)
    filled_tail = [f"{t.rstrip('。')}。\n" for t in procedure_pool]

    # 自检：任何没被替换掉的 `{占位符}` 都说明语料骨架有笔误，
    # 直接在此处报错，而不是把 `{周报}` 这种东西写进语料污染检索。
    for text in filled_body + filled_tail:
        leftover = _CLAUSE_RE.findall(text)
        if leftover:
            raise ValueError(
                f"语料模板存在未定义的占位符 {leftover}：{topic['name']} -> {text.strip()[:60]}"
            )

    # 长度收敛：前后缀固定约 330~420 字，正文条款每条 60~110 字，尾段条款约 90 字。
    # 先递增正文条数，同时尝试不同的尾段条数，取字数最接近 target 的一版；
    # 若所有组合都不足 800 字（条款池太短），取最长的一版兜底。
    prefix_len = len(header) + len(scope)

    def build(n_body: int, n_tail: int) -> str:
        parts = [header, scope]
        for i in range(n_body):
            parts.append(f"第{_cn_index(4 + i)}条 {filled_body[i]}\n")
        for j in range(n_tail):
            parts.append(f"第{_cn_index(4 + n_body + j)}条 {filled_tail[j]}\n")
        tail_start = 4 + n_body + n_tail
        parts.append(
            f"第{_cn_index(tail_start)}条 本{suffix}由{dept}负责制定、解释与修订，"
            f"自发布之日起施行；此前发布的与本{suffix}不一致的相关文件同时废止。\n\n"
            f"第{_cn_index(tail_start + 1)}条 员工应自觉遵守本{suffix}，违反规定的，"
            f"公司有权依据《员工奖惩管理办法》给予相应处理；造成经济损失的，依法追究赔偿责任。\n\n"
            f"第{_cn_index(tail_start + 2)}条 本{suffix}未尽事宜，按公司相关制度执行；"
            f"如与国家法律法规冲突，以法律法规为准。\n"
        )
        return "".join(parts)

    body_max = len(filled_body)
    tail_max = len(filled_tail)
    # 正文条款不少于 6 条：既要凑够字数，也不能退化成"只有总则和附则"的空壳
    candidates = []
    for nt in (1, 2, tail_max):
        for nb in range(min(6, body_max), body_max + 1):
            text = build(nb, nt)
            candidates.append(text)
            if len(text) >= 1500:
                break
    candidates.append(build(body_max, tail_max))

    # 优先挑 800~1500 字区间内最接近 target 的；没有落进区间的就取最长的一版
    in_range = [c for c in candidates if 800 <= len(c) <= 1500]
    if in_range:
        return min(in_range, key=lambda c: abs(len(c) - target))
    return max(candidates, key=len)


_CN_NUM = "一二三四五六七八九十"


def _cn_index(i: int) -> str:
    """4 -> 四，11 -> 十一（用于条款序号）。"""
    if i <= 10:
        return _CN_NUM[i - 1]
    if i < 20:
        return "十" + _CN_NUM[i - 11]
    return str(i)


def _safe_filename(text: str) -> str:
    """文件名清洗：去掉 Windows 非法字符。"""
    return re.sub(r'[<>:"/\\|?*]', "_", text)



